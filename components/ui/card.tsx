import * as React from "react";

import { cn } from "@/lib/utils";

function Card({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card"
      className={cn(
        // A hairline border and no shadow: cards read as sections of the page, not as things floating on it
        "flex flex-col gap-4 rounded-xl border border-border bg-card p-5 text-card-foreground",
        className,
      )}
      {...props}
    />
  );
}

function CardHeader({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card-header"
      className={cn("flex flex-col gap-1", className)}
      {...props}
    />
  );
}

function CardTitle({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card-title"
      className={cn(
        "flex items-center gap-1.5 text-sm font-medium text-muted-foreground",
        className,
      )}
      {...props}
    />
  );
}

function CardValue({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card-value"
      className={cn("text-2xl font-semibold tracking-tight text-foreground tabular-nums", className)}
      {...props}
    />
  );
}

function CardContent({ className, ...props }: React.ComponentProps<"div">) {
  return <div data-slot="card-content" className={cn(className)} {...props} />;
}

function CardFooter({ className, ...props }: React.ComponentProps<"div">) {
  return (
    <div
      data-slot="card-footer"
      className={cn("flex items-center", className)}
      {...props}
    />
  );
}

export { Card, CardHeader, CardTitle, CardValue, CardContent, CardFooter };
